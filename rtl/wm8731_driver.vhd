-- Title      : WM8731 driver
-- Project    : PoliMorph: a continuous touch synthesizer
-------------------------------------------------------------------------------
-- File       : wm8731_driver.vhd
-- Author     : Maurizio MARTINA
-- Company    : Politecnico di Torino
-- Created    : 2025-05-14
-- Last update: 2026-10-23
-- Platform   : DE1-SoC + MTL2 boards
-- Standard   : VHDL'93/02
-------------------------------------------------------------------------------
-- Description: This file contains a driver for the WM8731 audio codec. The
-- project is intended for the DE1-SoC board, but it is compabile with other
-- boards using the same codec e.g. DE10-Standard.
-- The driver is inspired by the driver developed by Prof. Scott Hauck and Kyle
-- Gagner at University of Washington and by Altera tutorials. The driver
-- receives the 50 MHz clock and generated a 48 kHz ADVANCE signal to sample audio values
-- generated by the audio engine. It requires a PLL to generate a 12.288 MHz
-- frequency, which is used to drive the clock pin of the WM8731 (AUD_XCK). The
-- audio format is left-justified with the WM8731 working in master mode
-- generating AUD_BCLK, DACLRCK and ADCLRCK. The driver configures the WM8731
-- via I2C and then it manages samples for the DAC.
-- NOTE: the ADC part is not used and it has not been tested.
-------------------------------------------------------------------------------

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity wm8731_driver is
  port (
    CLOCK_50 : in    std_logic;
    RESET_n  : in    std_logic;
    FPGA_I2C_SCLK : out   std_logic;
    FPGA_I2C_SDAT : inout std_logic;
    AUD_XCK     : out std_logic;
    AUD_BCLK    : in  std_logic;
    AUD_DACLRCK : in  std_logic;
    AUD_ADCLRCK : in  std_logic;
    AUD_ADCDAT  : in  std_logic;
    AUD_DACDAT  : out std_logic;
    DAC_LEFT  : in  std_logic_vector(23 downto 0);
    DAC_RIGHT : in  std_logic_vector(23 downto 0);
    ADC_LEFT  : out std_logic_vector(23 downto 0);
    ADC_RIGHT : out std_logic_vector(23 downto 0);
    ADVANCE   : out std_logic
  );
end entity wm8731_driver;

architecture rtl of wm8731_driver is


  -----------------------------------------------------------------------------
  -- Fractional PLL
  --   Input:    50.000 MHz
  --   Output 0: 12.288 MHz
  -- ----------------------------------------------------------
  component pll_audio is
    port (
      refclk   : in  std_logic;
      rst      : in  std_logic;
      outclk_0 : out std_logic;
      locked   : out std_logic
    );
  end component pll_audio;

  -- ----------------------------------------------------------
  -- I2C init sequencer
  -- ----------------------------------------------------------
  component wm8731_i2c_cfg is
    port (
      CLK      : in    std_logic;
      RST_n    : in    std_logic;
      I2C_SCL  : out   std_logic;
      I2C_SDA  : inout std_logic;
      CFG_DONE : out   std_logic
    );
  end component wm8731_i2c_cfg;

  -- ----------------------------------------------------------
  -- Internals
  -- ----------------------------------------------------------

  signal rst : std_logic;

  signal pll_locked : std_logic;
  signal cfg_done   : std_logic;
  signal int_rst_n  : std_logic;

  signal bclk_d1, bclk_d2, bclk_d3 : std_logic;
  signal lrck_d1, lrck_d2, lrck_d3 : std_logic;

  signal adat_d1, adat_d2 : std_logic;

  signal bclk_rise : std_logic;
  signal bclk_fall : std_logic;
  signal lrck_fall : std_logic;
  signal lrck_rise : std_logic;

  -- ----------------------------------------------------------
  -- Audio state machine
  -- sWAIT_CFG   : hold until I2C init completes
  -- sCHAN_LEFT  : serialising/deserialising left  channel
  -- sCHAN_RIGHT : serialising/deserialising right channel
  -- ----------------------------------------------------------
  type t_audio_state is (sWAIT_CFG, sCHAN_LEFT, sCHAN_RIGHT);
  signal audio_st : t_audio_state;

  -- DAC shift registers
  signal dac_l_sr : std_logic_vector(23 downto 0);
  signal dac_r_sr : std_logic_vector(23 downto 0);

  -- ADC shift registers
  signal adc_l_sr : std_logic_vector(23 downto 0);
  signal adc_r_sr : std_logic_vector(23 downto 0);

  -- Latched ADC outputs
  signal adc_left_r  : std_logic_vector(23 downto 0);
  signal adc_right_r : std_logic_vector(23 downto 0);

  -- Registered DACDAT output
  signal dacdat_r : std_logic;

  -- Bit counter
  signal bit_cnt : integer range 0 to 31;

begin

  -- ----------------------------------------------------------
  -- PLL
  -- ----------------------------------------------------------
  rst <= not(RESET_n);
  u_pll : pll_audio
    port map (
      refclk   => CLOCK_50,
      rst      => rst,
      outclk_0 => AUD_XCK,
      locked   => pll_locked
    );

  int_rst_n <= RESET_n and pll_locked;

  -- ----------------------------------------------------------
  -- I2C sequencer
  -- ----------------------------------------------------------
  u_i2c : wm8731_i2c_cfg
    port map (
      CLK      => CLOCK_50,
      RST_n    => int_rst_n,
      I2C_SCL  => FPGA_I2C_SCLK,
      I2C_SDA  => FPGA_I2C_SDAT,
      CFG_DONE => cfg_done
    );

  -- ----------------------------------------------------------
  -- Synchronisers
  -- ----------------------------------------------------------
  p_sync : process (CLOCK_50, int_rst_n) begin
    if int_rst_n = '0' then
      bclk_d1 <= '0'; bclk_d2 <= '0'; bclk_d3 <= '0';
      lrck_d1 <= '0'; lrck_d2 <= '0'; lrck_d3 <= '0';
      adat_d1 <= '0'; adat_d2 <= '0';
    elsif rising_edge(CLOCK_50) then
      -- BCLK
      bclk_d1 <= AUD_BCLK;    bclk_d2 <= bclk_d1; bclk_d3 <= bclk_d2;
      -- LRCLK
      lrck_d1 <= AUD_DACLRCK; lrck_d2 <= lrck_d1; lrck_d3 <= lrck_d2;
      -- ADCDAT
      adat_d1 <= AUD_ADCDAT;  adat_d2 <= adat_d1;
    end if;
  end process p_sync;

  -- Edge detection from the stabilised chain
  bclk_rise <= bclk_d2 and (not bclk_d3);
  bclk_fall <= (not bclk_d2) and bclk_d3;
  lrck_fall <= (not lrck_d2) and lrck_d3;
  lrck_rise <= lrck_d2 and (not lrck_d3);

  -- ----------------------------------------------------------
  -- Audio state machine + shift registers
  -- ----------------------------------------------------------
  p_audio : process (CLOCK_50, int_rst_n) begin
    if int_rst_n = '0' then
      audio_st    <= sWAIT_CFG;
      ADVANCE     <= '0';
      dacdat_r    <= '0';
      bit_cnt     <= 0;
      dac_l_sr    <= (others => '0');
      dac_r_sr    <= (others => '0');
      adc_l_sr    <= (others => '0');
      adc_r_sr    <= (others => '0');
      adc_left_r  <= (others => '0');
      adc_right_r <= (others => '0');

    elsif rising_edge(CLOCK_50) then
      ADVANCE <= '0';  -- default;

      -------------------------------------------------------------------------
      -- Block A: ADC input on every BCLK rising edge
      -- Captures up to 24 bits per channel.
      -------------------------------------------------------------------------
      if bclk_rise = '1' then
        case audio_st is
          when sCHAN_LEFT  =>
            if bit_cnt < 24 then
              adc_l_sr <= adc_l_sr(22 downto 0) & adat_d2;
            end if;
          when sCHAN_RIGHT =>
            if bit_cnt < 24 then
              adc_r_sr <= adc_r_sr(22 downto 0) & adat_d2;
            end if;
          when others => null;
        end case;
        if bit_cnt < 31 then
          bit_cnt <= bit_cnt + 1;
        end if;
      end if;

      -------------------------------------------------------------------------
      -- Block B: DAC output on every BCLK falling edge
      -------------------------------------------------------------------------
      if bclk_fall = '1' then
        case audio_st is
          when sCHAN_LEFT =>
            if bit_cnt >= 1 and bit_cnt < 24 then
              dacdat_r <= dac_l_sr(23);
              dac_l_sr <= dac_l_sr(22 downto 0) & '0';
            else
              dacdat_r <= '0';  -- padding
            end if;
          when sCHAN_RIGHT =>
            if bit_cnt >= 1 and bit_cnt < 24 then
              dacdat_r <= dac_r_sr(23);
              dac_r_sr <= dac_r_sr(22 downto 0) & '0';
            else
              dacdat_r <= '0';
            end if;
          when others =>
            dacdat_r <= '0';
        end case;
      end if;

      -------------------------------------------------------------------------
      -- Block C: LRCK FALLING edge = start of LEFT frame
      -------------------------------------------------------------------------
      if lrck_fall = '1' then
        if audio_st /= sWAIT_CFG then
          -- Complete right frame
          adc_right_r <= adc_r_sr;
          adc_r_sr    <= (others => '0');
          -- Load new DAC data
          dac_l_sr    <= DAC_LEFT(22 downto 0) & '0';
          dac_r_sr    <= DAC_RIGHT(22 downto 0) & '0';
          -- Drive bit 23 (MSB) of left channel immediately
          dacdat_r    <= DAC_LEFT(23);
          -- Notify user
          ADVANCE     <= '1';
        end if;
        bit_cnt  <= 0;
        audio_st <= sCHAN_LEFT;
      end if;

      -------------------------------------------------------------------------
      -- Block D: LRCK RISING edge = start of RIGHT frame
      -------------------------------------------------------------------------
      if lrck_rise = '1' then
        if audio_st = sCHAN_LEFT then
          -- Complete left frame
          adc_left_r  <= adc_l_sr;
          adc_l_sr    <= (others => '0');
          -- Drive bit 23 of right channel immediately
          dacdat_r    <= dac_r_sr(23);
          dac_r_sr    <= dac_r_sr(22 downto 0) & '0';
        end if;
        bit_cnt  <= 0;
        audio_st <= sCHAN_RIGHT;
      end if;

      -------------------------------------------------------------------------
      -- Block E: Wait for I2C configuration to complete
      -------------------------------------------------------------------------
      if audio_st = sWAIT_CFG then
        if cfg_done = '1' then
          null;
        end if;
      end if;

    end if;
  end process p_audio;

  -- ----------------------------------------------------------
  -- Output assignments
  -- ----------------------------------------------------------
  AUD_DACDAT <= dacdat_r;
  ADC_LEFT   <= adc_left_r;
  ADC_RIGHT  <= adc_right_r;

end architecture rtl;
